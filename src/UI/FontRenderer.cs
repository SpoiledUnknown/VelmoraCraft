    public FontRenderer()
    {
        GenerateFontTexture();
    }

    public int TextureID { get; private set; }

    private void GenerateFontTexture()
    {
        var pixels = new byte[ATLAS_WIDTH * ATLAS_HEIGHT * 4];

        for (var i = 0; i < 95; i++)
        {
            var col = i % COLS;
            var row = i / COLS;
            var startX = col * CHAR_WIDTH;
            var startY = row * CHAR_HEIGHT;

            for (var y = 0; y < 8; y++)
            {
                var b = FontData[i * 8 + y];
                for (var x = 0; x < 8; x++)
                {
                    var bit = ((b >> (7 - x)) & 1) == 1;
                    var pixelX = startX + x;
                    var pixelY = startY + (7 - y);
                    var idx = (pixelY * ATLAS_WIDTH + pixelX) * 4;

                    if (bit)
                    {
                        pixels[idx + 0] = 255;
                        pixels[idx + 1] = 255;
                        pixels[idx + 2] = 255;
                        pixels[idx + 3] = 255;
                    }
                    else
                    {
                        pixels[idx + 0] = 0;
                        pixels[idx + 1] = 0;
                        pixels[idx + 2] = 0;
                        pixels[idx + 3] = 0;
                    }
                }
            }
        }

        TextureID = GL.GenTexture();
        GL.BindTexture(TextureTarget.Texture2D, TextureID);
        GL.TexParameteri(TextureTarget.Texture2D, TextureParameterName.TextureMinFilter, (int)TextureMinFilter.Nearest);
        GL.TexParameteri(TextureTarget.Texture2D, TextureParameterName.TextureMagFilter, (int)TextureMagFilter.Nearest);
        GL.TexParameteri(TextureTarget.Texture2D, TextureParameterName.TextureWrapS, (int)TextureWrapMode.ClampToEdge);
        GL.TexParameteri(TextureTarget.Texture2D, TextureParameterName.TextureWrapT, (int)TextureWrapMode.ClampToEdge);

        GL.TexImage2D(
            TextureTarget.Texture2D,
            0,
            InternalFormat.Rgba,
            ATLAS_WIDTH,
            ATLAS_HEIGHT,
            0,
            PixelFormat.Rgba,
            PixelType.UnsignedByte,
            pixels
        );

        GL.BindTexture(TextureTarget.Texture2D, 0);
    }

    public (Vector2 uvMin, Vector2 uvMax) GetCharUV(char c)
    {
        if (c < 32 || c > 126) c = '?';
        var index = c - 32;
        var col = index % COLS;
        var row = index / COLS;

        var u0 = (float)(col * CHAR_WIDTH) / ATLAS_WIDTH;
        var u1 = (float)((col + 1) * CHAR_WIDTH) / ATLAS_WIDTH;

        // In our texture pixel array, row 0 is at index 0.
        // With standard OpenGL UVs, y=0 is at bottom unless inverted.
        // Matching ChunkMesher:
        var v0 = (float)(row * CHAR_HEIGHT) / ATLAS_HEIGHT;
        var v1 = (float)((row + 1) * CHAR_HEIGHT) / ATLAS_HEIGHT;

        return (new Vector2(u0, v0), new Vector2(u1, v1));
    }

    public void Bind()
    {
        GL.BindTexture(TextureTarget.Texture2D, TextureID);
    }

    public void Delete()
    {
        if (TextureID != 0)
        {
            GL.DeleteTexture(TextureID);
            TextureID = 0;
        }
    }
